"""Regenerate paper/_numbers.tex from results/*.json, the single source of truth
for every number in the paper.  Run after experiments/run_all.py."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = ROOT / "paper" / "_numbers.tex"


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def f2(x):
    return f"{x:.2f}"


def f3(x):
    return f"{x:.3f}"


def main():
    M = {}
    vf = load("verification_frontier")
    if vf:
        s = vf["verifier_soundness"]
        M["soundChecks"] = str(s["cross_checks"])
        M["soundAgree"] = str(s["agree"])
        b = vf["budgets"]
        lo, hi = b[0], b[-1]
        M["frLoC"] = str(lo["clauses"]); M["frLoAcc"] = f3(lo["accuracy"]["mean"])
        M["frLoMs"] = f"{lo['verify_us_per_query']['mean']/1000:.1f}"
        M["frHiC"] = str(hi["clauses"]); M["frHiAcc"] = f3(hi["accuracy"]["mean"])
        M["frHiMs"] = f"{hi['verify_us_per_query']['mean']/1000:.0f}"

    bd = load("bypass_discovery")
    if bd:
        s = bd["summary"]
        M["robustFrac"] = f2(s["frac_certified_robust"]["mean"])
        M["bypassFrac"] = f2(s["frac_bypassable"]["mean"])
        M["fuzzRecK"] = f2(s["fuzz_recall_of_bypasses"]["1000"]["mean"])
        M["verifyTok"] = f"{s['verify_us_per_query']['mean']/1000:.0f}"

    h = load("hardening")
    if h:
        s = h["summary"]
        M["bypInit"] = f"{s['bypass_initial']['mean']:.1f}"
        M["bypEmp"] = f"{s['bypass_empirical']['mean']:.1f}"
        M["bypCon"] = f"{s['bypass_constructive']['mean']:.1f}"
        M["accInit"] = f3(s["acc_initial"]["mean"])
        M["accEmp"] = f3(s["acc_empirical"]["mean"])
        M["accCon"] = f3(s["acc_constructive"]["mean"])
        M["clausesAdded"] = f"{s['clauses_added']['mean']:.0f}"
        M["lostGuar"] = f"{s['empirical_lost_guarantee']['mean']:.1f}"

    e = load("envelope_shift")
    if e:
        s = e["summary"]
        M["plainIn"] = f3(s["plain_in"]["mean"])
        M["plainOut"] = f3(s["plain_out"]["mean"])
        M["missEnv"] = f2(s["out_missed_rec"]["mean"])
        M["missBase"] = f2(s["base_out_missed_rec"]["mean"])
        M["soundRate"] = f2(s["sound"]["mean"])
        M["covEnv"] = f2(s["out_cov"]["mean"])
        M["covBase"] = f2(s["base_out_cov"]["mean"])
        if "base_matched_missed_rec" in s:
            M["missBaseM"] = f2(s["base_matched_missed_rec"]["mean"])
            M["covBaseM"] = f2(s["base_matched_cov"]["mean"])

    a = load("assurance_cert")
    if a:
        rates = [v["detection_rate"] for v in a["tampers"].values()] + [a["forged_signature_detection_rate"]]
        M["tamperRate"] = f2(min(rates))
        M["recheckRate"] = f2(a["recheck_pass_rate"])
        M["cxIndep"] = f2(a["counterexample_independent_rate"])
        M["forgedBySig"] = f2(a["forged_signature_caught_by_sig_rate"])
        M["nTamperClasses"] = str(len(a["tampers"]))

    sy = load("systems")
    if sy:
        M["zThree"] = f"{sy['backend_compare']['z3_us']/1000:.1f}"
        M["pySat"] = f"{sy['backend_compare']['pysat_us']/1000:.1f}"
        pc = sy["property_cost_us"]
        M["invMs"] = f"{pc['invariant']/1000:.0f}"
        M["radMs"] = f"{pc['robustness_radius']/1000:.0f}"
        M["monMs"] = f"{pc['monotone']/1000:.0f}"
        sc = sy["scale_clauses"]
        M["scLoC"] = str(sc[0]["clauses"]); M["scLoMs"] = f"{sc[0]['verify_us']/1000:.0f}"
        M["scHiC"] = str(sc[-1]["clauses"]); M["scHiMs"] = f"{sc[-1]['verify_us']/1000:.0f}"

    lines = ["% AUTO-GENERATED by scripts/paper_numbers.py, do not edit by hand."]
    for k, v in M.items():
        lines.append(f"\\renewcommand{{\\{k}}}{{{v}}}")
        print(f"  {k} = {v}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(M)} macros)")


if __name__ == "__main__":
    main()
